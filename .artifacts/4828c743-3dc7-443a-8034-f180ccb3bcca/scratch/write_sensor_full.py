import os

lines = []
lines.append("package com.example.camara")
lines.append("")
lines.append("import android.annotation.TargetApi")
lines.append("import android.content.Context")
lines.append("import android.hardware.camera2.CameraCharacteristics")
lines.append("import android.hardware.camera2.CameraManager")
lines.append("import android.os.Build")
lines.append("import android.util.Log")
lines.append("import android.util.Size")
lines.append("import android.view.Surface")
lines.append("import android.view.SurfaceTexture")
lines.append("import java.util.concurrent.CopyOnWriteArrayList")
lines.append("")
lines.append("object SensorScanner {")
lines.append("")
lines.append("    private const val TAG = \"VIVO_CAM_SCAN\"")
lines.append("")
lines.append("    data class SensorInfo(")
lines.append("        val logicalId: String,")
lines.append("        val physicalId: String,")
lines.append("        val isLogical: Boolean,")
lines.append("        val lensFacing: Int?,")
lines.append("        val focalLengthMm: Double?,")
lines.append("        val isoMin: Int?,")
lines.append("        val isoMax: Int?,")
lines.append("        val exposureMinNs: Long?,")
lines.append("        val exposureMaxNs: Long?,")
lines.append("        val minFocusDistance: Float?,")
lines.append("        val supportedFpsRanges: List<Pair<Int, Int>>,")
lines.append("        val surfaceTextureResolutions: List<Size>,")
lines.append("        val physicalCameraIds: List<String>,")
lines.append("    )")
lines.append("")
lines.append("    @TargetApi(Build.VERSION_CODES.P)")
lines.append("    fun scanCameras(context: Context): List<SensorInfo> {")
lines.append("        val manager = getCameraManager(context)")
lines.append("        val results = CopyOnWriteArrayList<SensorInfo>()")
lines.append("")
lines.append("        val cameraIds = try {")
lines.append("            manager.cameraIdList")
lines.append("        } catch (e: Exception) {")
lines.append("            Log.e(TAG, \"Fallo al obtener cameraIdList: \" + e.message)")
lines.append("            return results")
lines.append("        }")
lines.append("")
lines.append("        Log.d(TAG, \"=== INICIO ESCANEO HARDWARE CAMARA ===\")")
lines.append("        Log.d(TAG, \"IDs logicos detectados: \" + cameraIds.toList())")
lines.append("")
lines.append("        for (logicalId in cameraIds) {")
lines.append("            if (logicalId == \"0\") continue")
lines.append("")
lines.append("            val logicalSensor = scanLogicalSensor(manager, logicalId, emptyList())")
lines.append("            if (logicalSensor != null) results.add(logicalSensor)")
lines.append("")
lines.append("            val physicalIds = getPhysicalCameraIds(manager, logicalId)")
lines.append("            for (physicalId in physicalIds) {")
lines.append("                val physicalSensor = scanPhysicalSensor(manager, logicalId, physicalId)")
lines.append("                if (physicalSensor != null) results.add(physicalSensor)")
lines.append("            }")
lines.append("        }")
lines.append("")
lines.append("        results.forEach { dumpSensorInfo(it) }")
lines.append("        return results")
lines.append("    }")
lines.append("")
lines.append("    private fun getCameraManager(context: Context): CameraManager {")
lines.append("        return context")
lines.append("            .getDeclaredMethod(\"getCameraManager\")")
lines.append("            .let { it.invoke(context) as CameraManager }")
lines.append("    }")
lines.append("}")

