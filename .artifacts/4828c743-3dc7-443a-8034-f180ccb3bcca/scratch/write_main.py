A("import android.hardware.camera2.params.SessionConfiguration")
A("import java.util.concurrent.Executor")
A("import java.util.concurrent.Executors")
A("")
A("class MainActivity : AppCompatActivity() {")
A("")
A("    private val tag = \"VIVO_CAM_SCAN\"")
A("    private lateinit var textureView: TextureView")
A("    private lateinit var topPanel: LinearLayout")
A("    private lateinit var bottomPanel: LinearLayout")
A("    private lateinit var statusText: TextView")
A("    private lateinit var isoBar: SeekBar")
A("    private lateinit var shutterBar: SeekBar")
A("    private lateinit var isoLabel: TextView")
A("    private lateinit var shutterLabel: TextView")
A("")
A("    private lateinit var cameraManager: CameraManager")
A("    private var cameraDevice: CameraDevice? = null")
A("    private var captureSession: CameraCaptureSession? = null")
A("    private var previewRequestBuilder: CaptureRequest.Builder? = null")
A("    private var selectedPhysicalId: String? = \"0\"")
A("    private var isLogical0 = true")
A("    private var currentIso = 800")
A("    private var currentShutterNs: Long = 20000000L")
A("    private val executor = Executors.newSingleThreadExecutor()")
A("")
A("    override fun onCreate(savedInstanceState: Bundle?) {")
A("        super.onCreate(savedInstanceState)")
A("        supportActionBar?.hide()")
A("")
A("        val root = FrameLayout(this)")
A("        setContentView(root)")
A("")
A("        textureView = TextureView(this)")
A("        textureView.surfaceTextureListener = object : TextureView.SurfaceTextureListener {")
A("            override fun onSurfaceTextureAvailable(s: SurfaceTexture, w: Int, h: Int) {")
A("                s.setDefaultBufferSize(1920, 1080)")
A("                openCameraWithCurrentSelection()")
A("            }")
A("            override fun onSurfaceTextureSizeChanged(s: SurfaceTexture, w: Int, h: Int) {}")
A("            override fun onSurfaceTextureDestroyed(s: SurfaceTexture): Boolean = true")
A("            override fun onSurfaceTextureUpdated(s: SurfaceTexture) {}")
A("        }")
A("        root.addView(textureView, FrameLayout.LayoutParams(-1, -1))")
A("")
A("        topPanel = LinearLayout(this).apply {")
A("            orientation = LinearLayout.HORIZONTAL")
A("            setBackgroundColor(0xAA000000.toInt())")
A("            setPadding(0, 100, 0, 0)")
A("        }")
A("        root.addView(topPanel, FrameLayout.LayoutParams(-1, -2, Gravity.TOP))")
A("")
A("        val btnParams = LinearLayout.LayoutParams(0, LinearLayout.LayoutParams.WRAP_CONTENT, 1f)")
A("        fun addLensBtn(label: String, id: String) {")
A("            val btn = Button(this).apply {")
A("                text = label")
A("                setOnClickListener {")
A("                    selectedPhysicalId = id")
A("                    isLogical0 = (id == \"0\")")
A("                    closeCamera()")
A("                    openCameraWithCurrentSelection()")
A("                }")
A("            }")
A("            topPanel.addView(btn, btnParams)")
A("        }")
A("        addLensBtn(\"L 0\", \"0\")")
A("        addLensBtn(\"L 2\", \"2\")")
A("        addLensBtn(\"L 3\", \"3\")")
A("        addLensBtn(\"L 4\", \"4\")")
A("")
A("        bottomPanel = LinearLayout(this).apply {")
A("            orientation = LinearLayout.VERTICAL")
A("            setBackgroundColor(0xAA000000.toInt())")
A("            setPadding(0, 0, 0, 120)")
A("        }")
A("        root.addView(bottomPanel, FrameLayout.LayoutParams(-1, -2, Gravity.BOTTOM))")
A("")
A("        isoLabel = TextView(this).apply { text = \"ISO: $currentIso\"; setTextColor(0xFFFFFFFF.toInt()) }")
A("        bottomPanel.addView(isoLabel)")
A("")
A("        isoBar = SeekBar(this).apply {")
A("            max = 6350")
A("            progress = currentIso - 50")
A("            setOnSeekBarChangeListener(object : SeekBar.OnSeekBarChangeListener {")
A("                override fun onProgressChanged(sb: SeekBar, p: Int, fromUser: Boolean) {")
A("                    currentIso = p + 50")
A("                    isoLabel.text = \"ISO: $currentIso\"")
A("                    applyManualSettings()")
A("                }")
A("                override fun onStartTrackingTouch(sb: SeekBar) {}")
A("                override fun onStopTrackingTouch(sb: SeekBar) {}")
A("            })")
A("        }")
A("        bottomPanel.addView(isoBar)")
A("")
A("        shutterLabel = TextView(this).apply { text = \"Shutter\"; setTextColor(0xFFFFFFFF.toInt()) }")
A("        bottomPanel.addView(shutterLabel)")
A("")
A("        shutterBar = SeekBar(this).apply {")
A("            max = 100")
A("            progress = 50")
A("            setOnSeekBarChangeListener(object : SeekBar.OnSeekBarChangeListener {")
A("                override fun onProgressChanged(sb: SeekBar, p: Int, fromUser: Boolean) {")
A("                    currentShutterNs = 1000000L + (41666666L - 1000000L) * p / 100")
A("                    shutterLabel.text = \"Shutter: ${currentShutterNs / 1000000}ms\"")
A("                    applyManualSettings()")
A("                }")
A("                override fun onStartTrackingTouch(sb: SeekBar) {}")
A("                override fun onStopTrackingTouch(sb: SeekBar) {}")
A("            })")
A("        }")
A("        bottomPanel.addView(shutterBar)")
A("")
A("        statusText = TextView(this).apply { text = \"\"; setTextColor(0xFFFF0000.toInt()) }")
A("        root.addView(statusText, FrameLayout.LayoutParams(-2, -2, Gravity.TOP or Gravity.END))")
A("")
A("        cameraManager = getSystemService(Context.CAMERA_SERVICE) as CameraManager")
A("        if (ContextCompat.checkSelfPermission(this, Manifest.permission.CAMERA) == PackageManager.PERMISSION_GRANTED) {")
A("            if (textureView.isAvailable) openCameraWithCurrentSelection()")
A("        } else {")
A("            ActivityCompat.requestPermissions(this, arrayOf(Manifest.permission.CAMERA), 42)")
A("        }")
A("    }")
A("")
A("    private fun openCameraWithCurrentSelection() {")
A("        try {")
A("            cameraManager.openCamera(\"0\", object : CameraDevice.StateCallback() {")
A("                override fun onOpened(camera: CameraDevice) {")
A("                    cameraDevice = camera")
A("                    startPreviewSession(false)")
A("                }")
A("                override fun onDisconnected(camera: CameraDevice) {")
A("                    camera.close()")
A("                    cameraDevice = null")
A("                }")
A("                override fun onError(camera: CameraDevice, error: Int) {")
A("                    camera.close()")
A("                    cameraDevice = null")
A("                    logError(\"Camera Error: $error\")")
A("                }")
A("            }, null)")
A("        } catch (e: Exception) {")
A("            logError(\"Open Error: ${e.message}\")")
A("        }")
A("    }")
A("")
A("    private fun startPreviewSession(isFallback: Boolean) {")
A("        val device = cameraDevice ?: return")
A("        try {")
A("            val surfaceTexture = textureView.surfaceTexture ?: return")
A("            surfaceTexture.setDefaultBufferSize(1920, 1080)")
A("            val surface = Surface(surfaceTexture)")
A("            val outputConfig = OutputConfiguration(surface)")
A("")
A("            if (!isFallback && !isLogical0 && selectedPhysicalId != null) {")
A("                outputConfig.setPhysicalCameraId(selectedPhysicalId)")
A("            }")
A("")
A("            val sessionConfig = SessionConfiguration(")
A("                SessionConfiguration.SESSION_REGULAR,")
A("                listOf(outputConfig),")
A("                executor,")
A("                object : CameraCaptureSession.StateCallback() {")
A("                    override fun onConfigured(session: CameraCaptureSession) {")
A("                        captureSession = session")
A("                        try {")
A("                            val builder = device.createCaptureRequest(CameraDevice.TEMPLATE_RECORD)")
A("                            builder.addTarget(surface)")
A("                            previewRequestBuilder = builder")
A("                            applyManualSettingsInternal(builder)")
A("                            session.setRepeatingRequest(builder.build(), null, null)")
A("                        } catch (e: Exception) {")
A("                            logError(\"Session Builder Error: ${e.message}\")")
A("                        }")
A("                    }")
A("                    override fun onConfigureFailed(session: CameraCaptureSession) {")
A("                        logError(\"Config Failed (Fallback: $isFallback)\")")
A("                        if (!isFallback && !isLogical0) {")
A("                            closeCamera()")
A("                            try {")
A("                                cameraManager.openCamera(selectedPhysicalId!!, object : CameraDevice.StateCallback() {")
A("                                    override fun onOpened(c: CameraDevice) {")
A("                                        cameraDevice = c")
A("                                        startPreviewSession(true)")
A("                                    }")
A("                                    override fun onDisconnected(c: CameraDevice) { c.close(); cameraDevice = null }")
A("                                    override fun onError(c: CameraDevice, err: Int) { c.close(); cameraDevice = null; logError(\"Fallback Open Error: $err\") }")
A("                                }, null)")
A("                            } catch (ex: Exception) {")
A("                                logError(\"Fallback Exception: ${ex.message}\")")
A("                            }")
A("                        }")
A("                    }")
A("                }")
A("            )")
A("")
A("            device.createCaptureSession(sessionConfig)")
A("        } catch (e: Exception) {")
A("            logError(\"Session Error: ${e.message}\")")
A("        }")
A("    }")
A("")
A("    private fun applyManualSettingsInternal(builder: CaptureRequest.Builder) {")
A("        builder.set(CaptureRequest.CONTROL_AE_MODE, CaptureRequest.CONTROL_AE_MODE_OFF)")
A("        builder.set(CaptureRequest.SENSOR_SENSITIVITY, currentIso)")
A("        builder.set(CaptureRequest.SENSOR_EXPOSURE_TIME, currentShutterNs)")
A("        builder.set(CaptureRequest.EDGE_MODE, CaptureRequest.EDGE_MODE_OFF)")
A("        builder.set(CaptureRequest.NOISE_REDUCTION_MODE, CaptureRequest.NOISE_REDUCTION_MODE_OFF)")
A("    }")
A("")
A("    private fun applyManualSettings() {")
A("        val builder = previewRequestBuilder ?: return")
A("        applyManualSettingsInternal(builder)")
A("        try {")
A("            captureSession?.setRepeatingRequest(builder.build(), null, null)")
A("        } catch (e: Exception) {")
A("            Log.e(tag, \"Apply error\", e)")
A("        }")
A("    }")
A("")
A("    private fun closeCamera() {")
A("        captureSession?.close()")
A("        captureSession = null")
A("        cameraDevice?.close()")
A("        cameraDevice = null")
A("    }")
A("")
A("    private fun logError(msg: String) {")
A("        runOnUiThread { statusText.text = msg }")
A("        Log.e(tag, msg)")
A("    }")
A("")
A("    override fun onPause() {")
A("        super.onPause()")
A("        closeCamera()")
A("    }")
A("")
A("    override fun onDestroy() {")
A("        super.onDestroy()")
A("        closeCamera()")
A("    }")
A("}")
