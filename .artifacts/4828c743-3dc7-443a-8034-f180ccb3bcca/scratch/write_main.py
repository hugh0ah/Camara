A("import android.widget.LinearLayout")
A("import android.widget.SeekBar")
A("import android.widget.TextView")
A("import androidx.appcompat.app.AppCompatActivity")
A("import androidx.core.app.ActivityCompat")
A("import androidx.core.content.ContextCompat")
A("import android.hardware.camera2.CameraDevice")
A("import android.hardware.camera2.CameraManager")
A("import android.hardware.camera2.CameraCaptureSession")
A("import android.hardware.camera2.CaptureRequest")
